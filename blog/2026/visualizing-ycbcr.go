func addAlbumArt(dst *image.RGBA, which int) error {
	basename := albumNames[which]
	basename = strings.ReplaceAll(basename, "; ", "_")
	basename = strings.ReplaceAll(basename, " ", "-")
	basename = strings.ReplaceAll(basename, "'", "")
	basename = strings.ReplaceAll(basename, ",", "")
	basename = strings.ReplaceAll(basename, ".", "")
	basename = strings.ReplaceAll(basename, "?", "")
	basename = strings.ReplaceAll(basename, "ö", "o")

	srcFile, err := os.Open("../data/album-art-jpegs/" + basename + ".jpeg")
	if err != nil {
		return err
	}
	defer srcFile.Close()

	src, _, err := image.Decode(srcFile)
	if err != nil {
		return err
	}

	baseX := ((which % 3) * 768)
	baseY := ((which / 3) * 384)

	draw.Draw(dst, dst.Bounds().Add(image.Point{baseX + (3 * 32), baseY + 32}), src, image.Point{}, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{baseX + (13 * 32), baseY + 32}), makeChromaScatterplot(src), image.Point{}, draw.Src)

	c := freetype.NewContext()
	c.SetDPI(72)
	c.SetFontSize(18)
	c.SetClip(dst.Bounds())
	c.SetDst(dst)
	c.SetHinting(font.HintingFull)
	c.SetSrc(image.White)

	name := albumNames[which]
	i := strings.IndexByte(name, ';')

	c.SetFont(regularFont)
	c.DrawString(name[:i], freetype.Pt(baseX+(1.5*64), baseY+320))
	c.SetFont(italicFont)
	c.DrawString(name[i+2:], freetype.Pt(baseX+(1.5*64), baseY+344))

	return nil
}

func makeChromaScatterplot(src image.Image) *image.RGBA {
	dst := image.NewRGBA(image.Rect(0, 0, 256, 256))

	for i, v := range uncompressedMask {
		gray := 0x30 + (v >> 4)
		dst.SetRGBA(i%256, i/256, color.RGBA{gray, gray, gray, 0xFF})
	}

	bgColor := color.RGBA{0x30, 0x30, 0x30, 0xFF}
	for i := range 256 {
		dst.SetRGBA(i, 255-0x40, bgColor)
		dst.SetRGBA(i, 255-0x80, bgColor)
		dst.SetRGBA(i, 255-0xC0, bgColor)
		dst.SetRGBA(0x40, i, bgColor)
		dst.SetRGBA(0x80, i, bgColor)
		dst.SetRGBA(0xC0, i, bgColor)
	}

	if src != nil {
		src1 := src.(image.RGBA64Image)
		bounds := src1.Bounds()
		for y := bounds.Min.Y; y < bounds.Max.Y; y++ {
			for x := bounds.Min.X; x < bounds.Max.X; x++ {
				c := src1.RGBA64At(x, y)
				_, cb, cr := color.RGBToYCbCr(
					uint8(c.R>>8),
					uint8(c.G>>8),
					uint8(c.B>>8))
				dst.Set(int(cb), 255-int(cr), color.YCbCr{0x80, cb, cr})
			}
		}
	}

	return dst
}

func makeCircle() *image.RGBA {
	m := image.NewRGBA(image.Rect(0, 0, 64, 64))

	const radius = 32
	for j := -radius; j <= +radius; j++ {
		for i := -radius; i <= +radius; i++ {
			d2 := (i * i) + (j * j)
			if d2 < (24 * 24) {
				m.SetRGBA(32+i, 32+j, color.RGBA{0xFF, 0xFF, 0xFF, 0xFF})
			} else if d2 < (32 * 32) {
				m.SetRGBA(32+i, 32+j, color.RGBA{0x00, 0x00, 0x00, 0xFF})
			}
		}
	}

	return downsample2x(downsample2x(m))
}

func downsample2x(src image.Image) *image.RGBA {
	src1, ok := src.(*image.RGBA)
	if !ok {
		src1 = image.NewRGBA(src.Bounds())
		draw.Draw(src1, src1.Bounds(), src, src.Bounds().Min, draw.Src)
	}

	avg := func(a uint8, b uint8, c uint8, d uint8) uint8 {
		return uint8((int(a) + int(b) + int(c) + int(d) + 2) / 4)
	}

	sBounds := src1.Bounds()
	dBounds := image.Rectangle{
		Min: image.Point{
			sBounds.Min.X / 2,
			sBounds.Min.Y / 2,
		},
		Max: image.Point{
			sBounds.Max.X / 2,
			sBounds.Max.Y / 2,
		},
	}
	dst := image.NewRGBA(dBounds)
	for y := dBounds.Min.Y; y < dBounds.Max.Y; y++ {
		for x := dBounds.Min.X; x < dBounds.Max.X; x++ {
			c0 := src1.RGBAAt((2*x)+0, (2*y)+0)
			c1 := src1.RGBAAt((2*x)+1, (2*y)+0)
			c2 := src1.RGBAAt((2*x)+0, (2*y)+1)
			c3 := src1.RGBAAt((2*x)+1, (2*y)+1)
			dst.SetRGBA(x, y, color.RGBA{
				R: avg(c0.R, c1.R, c2.R, c3.R),
				G: avg(c0.G, c1.G, c2.G, c3.G),
				B: avg(c0.B, c1.B, c2.B, c3.B),
				A: avg(c0.A, c1.A, c2.A, c3.A),
			})
		}
	}
	return dst
}

var uncompressedMask = func() []byte {
	u, _ := io.ReadAll(flate.NewReader(bytes.NewReader(compressedMask[:])))
	return u
}()

func makeCompressedMask() {
	const dimension = 1024

	m := image.NewRGBA(image.Rect(0, 0, dimension, dimension))

	const N = 2 * dimension
	for i := range N + 1 {
		r := float64(i) / N
		for j := range N + 1 {
			g := float64(j) / N
			for k := range N + 1 {
				b := float64(k) / N

				// https://www.w3.org/Graphics/JPEG/jfif3.pdf
				u := (-0.1687 * r) + (-0.3313 * g) + (+0.5000 * b)
				v := (+0.5000 * r) + (-0.4187 * g) + (-0.0813 * b)

				u8 := int(((u + 0.5) * (dimension - 1)) + 0.5)
				v8 := int(((v + 0.5) * (dimension - 1)) + 0.5)

				m.SetRGBA(u8, (dimension-1)-v8, color.RGBA{
					R: 0xFF,
					G: 0xFF,
					B: 0xFF,
					A: 0xFF,
				})
			}
		}
	}

	for m.Bounds().Dx() > 256 {
		m = downsample2x(m)
	}

	mask := make([]byte, 256*256)
	for y := range 256 {
		for x := range 256 {
			c := m.RGBAAt(x, y)
			mask[(256*y)+x] = (c.A >> 4) * 0x11
		}
	}

	buf := &bytes.Buffer{}
	w, _ := flate.NewWriter(buf, flate.BestCompression)
	w.Write(mask)
	w.Close()

	compressed := buf.Bytes()
	for i, v := range compressed {
		fmt.Printf("0x%02X,", v)
		if (i & 15) == 15 {
			fmt.Println()
		}
	}
}

