func do1YcbcrParticles(filename string, src *image.YCbCr, t int) error {
	const nSteps = 16
	calcLambda := func(x int, y int, t int) int {
		diff := int(noise[((x>>5)^x)&31][((y>>5)^y)&31] >> 4)
		return min(nSteps, t-diff-(y>>4)-1)
	}

	dst := image.NewRGBA(image.Rect(0, 0, 768, 512))
	draw.Draw(dst, dst.Bounds(), &image.Uniform{color.Gray{0x30}}, image.Point{}, draw.Src)

	draw.Draw(dst, dst.Bounds().Add(image.Point{64, 154}), src, src.Bounds().Min, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{448, 128}), makeChromaScatterplot(nil), image.Point{}, draw.Src)

	srcH := src.Bounds().Dy()
	srcW := src.Bounds().Dx()

	for sy := range srcH {
		for sx := range srcW {
			lambda := calcLambda(sx, sy, t)
			if lambda < 0 {
				continue
			}
			startx := sx + 64
			starty := sy + 154

			c := src.RGBA64At(sx, sy)
			yy, _, _ := color.RGBToYCbCr(
				uint8(c.R>>8),
				uint8(c.G>>8),
				uint8(c.B>>8))

			dst.SetRGBA(startx, starty, color.RGBA{yy, yy, yy, 0xFF})
		}
	}

	for sy := range srcH {
		for sx := range srcW {
			lambda := calcLambda(sx, sy, t)
			if lambda < 0 {
				continue
			}
			startx := sx + 64
			starty := sy + 154

			c := src.RGBA64At(sx, sy)
			_, cb, cr := color.RGBToYCbCr(
				uint8(c.R>>8),
				uint8(c.G>>8),
				uint8(c.B>>8))

			endx := 448 + int(cb)
			endy := 384 - int(cr)

			k := (lambda * 16) + (int(noise[sy&31][sx&31]&15) - 8)
			w1 := cosines[max(0, min(256, k))]
			w0 := 0x10000 - w1

			dx := ((w0 * startx) + (w1 * endx)) / 0x10000
			dy := ((w0 * starty) + (w1 * endy)) / 0x10000
			dst.Set(dx, dy, color.YCbCr{0x80, cb, cr})
		}
	}

	f, err := os.Create(filename)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, dst)
}

