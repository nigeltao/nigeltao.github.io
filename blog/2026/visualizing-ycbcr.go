func doYcbcrAtConstantG() error {
	const N = 16
	for i := range (2 * N) + 1 {
		filename := fmt.Sprintf("/tmp/yccp-%03d.png", i)
		fmt.Println(filename)

		c := math.Cos(math.Pi * float64(i) / N)

		if err := do1YcbcrAtConstantG(filename, (1-c)/2); err != nil {
			return err
		}
	}

	// Stitch the resultant PNGs together with:
	//
	// apngasm ycbcr-at-constant-g.png /tmp/yccp-000.png

	return nil
}

func do1YcbcrAtConstantG(filename string, constantG float64) error {
	const dimension = 1024

	m := image.NewRGBA(image.Rect(0, 0, dimension, dimension))
	draw.Draw(m, m.Bounds(), &image.Uniform{color.Gray{0x30}}, image.Point{}, draw.Src)

	poke := func(r float64, g float64, b float64) {
		// https://www.w3.org/Graphics/JPEG/jfif3.pdf
		u := (-0.1687 * r) + (-0.3313 * g) + (+0.5000 * b)
		v := (+0.5000 * r) + (-0.4187 * g) + (-0.0813 * b)

		r8 := int((r * 255) + 0.5)
		g8 := int((g * 255) + 0.5)
		b8 := int((b * 255) + 0.5)

		u8 := int(((u + 0.5) * (dimension - 1)) + 0.5)
		v8 := int(((v + 0.5) * (dimension - 1)) + 0.5)

		m.SetRGBA(u8, (dimension-1)-v8, color.RGBA{
			R: uint8(max(0x00, min(0xFF, r8))),
			G: uint8(max(0x00, min(0xFF, g8))),
			B: uint8(max(0x00, min(0xFF, b8))),
			A: 0xFF,
		})
	}

	const N = 2 * dimension
	for i := range N + 1 {
		for j := range N + 1 {
			r := float64(i) / N
			b := float64(j) / N
			poke(r, constantG, b)
		}
	}

	for m.Bounds().Dx() > 256 {
		m = downsample2x(m)
	}

	bgColor := color.RGBA{0x40, 0x40, 0x40, 0xFF}
	for i := range 256 {
		m.SetRGBA(i, 255-0x00, bgColor)
		m.SetRGBA(i, 255-0x40, bgColor)
		m.SetRGBA(i, 255-0x80, bgColor)
		m.SetRGBA(i, 255-0xC0, bgColor)
		m.SetRGBA(i, 255-0xFF, bgColor)
		m.SetRGBA(0x00, i, bgColor)
		m.SetRGBA(0x40, i, bgColor)
		m.SetRGBA(0x80, i, bgColor)
		m.SetRGBA(0xC0, i, bgColor)
		m.SetRGBA(0xFF, i, bgColor)
	}

	dst := image.NewRGBA(image.Rect(0, 0, 768, 384))
	draw.Draw(dst, dst.Bounds(), &image.Uniform{color.Gray{0x30}}, image.Point{}, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{14 * 32, 64}), m, image.Point{}, draw.Src)

	g := uint8((constantG * 255) + 0.5)
	for r := range 256 {
		for b := range 256 {
			dst.SetRGBA((2*32)+b, 64+(255-r), color.RGBA{uint8(r), g, uint8(b), 0xFF})
		}
	}

	for i := range 16 {
		j := i + 256
		dst.SetRGBA((2*32)+j, 64+(255-0), bgColor)
		dst.SetRGBA((2*32)+0, 64+(255-j), bgColor)
		dst.SetRGBA((14*32)+j, 64+(255-128), bgColor)
		dst.SetRGBA((14*32)+128, 64+(255-j), bgColor)
	}

	circle := makeCircle()
	draw.Draw(dst, dst.Bounds().Add(image.Point{0x240 - 8, 0x0BF - 8}), circle, image.Point{}, draw.Over)
	draw.Draw(dst, dst.Bounds().Add(image.Point{0x040 - 8 + int(g), 0x13F - 8 - int(g)}), circle, image.Point{}, draw.Over)

	c := freetype.NewContext()
	c.SetDPI(72)
	c.SetFontSize(18)
	c.SetClip(dst.Bounds())
	c.SetDst(dst)
	c.SetHinting(font.HintingFull)
	c.SetSrc(image.White)
	c.SetFont(regularFont)

	c.DrawString("R ", freetype.Pt(0x040-6, 0x03F-16))
	c.DrawString("B ", freetype.Pt(0x140+16, 0x13F+6))
	c.DrawString("Cr", freetype.Pt(0x240-9, 0x03F-16))
	c.DrawString("Cb", freetype.Pt(0x2C0+16, 0x0BF+6))
	c.DrawString("0 ", freetype.Pt(0x040-6, 0x13F+24))
	c.DrawString("½ ", freetype.Pt(0x0C0-6, 0x13F+24))
	c.DrawString("1 ", freetype.Pt(0x140-6, 0x13F+24))
	c.DrawString("-½", freetype.Pt(0x1C0-11, 0x13F+24))
	c.DrawString("+0", freetype.Pt(0x240-11, 0x13F+24))
	c.DrawString("+½", freetype.Pt(0x2C0-11, 0x13F+24))

	c.DrawString(fmt.Sprintf("G ≈ %.03f", constantG), freetype.Pt(0x140+26, 0x0BF-16))

	f, err := os.Create(filename)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, dst)
}

func doYcbcrLumaPlusChroma() error {
	srcFile, err := os.Open("basantotsav.jpeg")
	if err != nil {
		return err
	}
	defer srcFile.Close()
	src0, _, err := image.Decode(srcFile)
	if err != nil {
		return err
	}
	src1 := src0.(*image.YCbCr)

	bounds := src1.Bounds()

	luma := image.NewRGBA(bounds)
	chma := image.NewRGBA(bounds)

	for y := bounds.Min.Y; y < bounds.Max.Y; y++ {
		for x := bounds.Min.X; x < bounds.Max.X; x++ {
			c := src1.RGBA64At(x, y)
			yy, cb, cr := color.RGBToYCbCr(
				uint8(c.R>>8),
				uint8(c.G>>8),
				uint8(c.B>>8))
			luma.Set(x, y, color.YCbCr{yy, 0x80, 0x80})
			chma.Set(x, y, color.YCbCr{0x80, cb, cr})
		}
	}

	dst := image.NewRGBA(image.Rect(0, 0, 1024, 384))
	draw.Draw(dst, dst.Bounds(), &image.Uniform{color.Gray{0x30}}, image.Point{}, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{66 + 0*320, 64}), src1, image.Point{}, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{66 + 1*320, 64}), luma, image.Point{}, draw.Src)
	draw.Draw(dst, dst.Bounds().Add(image.Point{66 + 2*320, 64}), chma, image.Point{}, draw.Src)

	c := freetype.NewContext()
	c.SetDPI(72)
	c.SetFontSize(32)
	c.SetClip(dst.Bounds())
	c.SetDst(dst)
	c.SetHinting(font.HintingFull)
	c.SetSrc(image.White)
	c.SetFont(regularFont)

	c.DrawString("(R, G, B)      ", freetype.Pt((0.5*320)-36, 320))
	c.DrawString("≡              ", freetype.Pt((1.0*320)+20, 320))
	c.DrawString("Luma (Y′)      ", freetype.Pt((1.5*320)-36, 320))
	c.DrawString("+              ", freetype.Pt((2.0*320)+20, 320))
	c.DrawString("Chroma (Cb, Cr)", freetype.Pt((2.5*320)-84, 320))

	return png.Encode(os.Stdout, dst)
}

